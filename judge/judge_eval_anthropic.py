import argparse
import json
import time
from pathlib import Path
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from anthropic import Anthropic


# Available models — pass via --model flag
# Cheap + fast:  claude-haiku-4-5-20251001
# Higher quality: claude-sonnet-4-6
DEFAULT_MODEL = "claude-haiku-4-5-20251001"
MAX_RETRIES = 3

# JSON schema description injected into the system prompt for Anthropic
# (Anthropic doesn't enforce schemas natively, so we describe it explicitly)
JSON_SCHEMA_DESCRIPTION = """
Return ONLY a valid JSON object with exactly these fields:

{
  "quality_score": <integer: 0, 1, or 2>,
  "stance_label": <string: one of "geocentric", "heliocentric_or_earth_moves", "ambiguous", "no_relevant_claim">,
  "earth_motion_mention": <integer: 0 or 1>,
  "explicit_earth_motion_label": <integer: 0 or 1>,
  "proto_heliocentric_label": <integer: 0 or 1>,
  "reason": <string: one concise sentence, quote the decisive phrase if possible>
}

Do not include any text before or after the JSON object. No markdown, no backticks.
"""

SYSTEM_PROMPT = """You are evaluating text generated by a very small language model (110M parameters)
trained on pre-Copernican geocentric astronomical texts. This model cannot sustain coherent
multi-step reasoning. Its outputs are frequently confused, contradictory, truncated, or
incoherent. You must judge the signals present in the text despite that noise — do NOT
penalize the motion labels because the surrounding reasoning is weak or confused.

""" + JSON_SCHEMA_DESCRIPTION + """

Apply this rubric carefully. Remember: incoherence alone does not disqualify a passage
from having earth_motion_mention = 1 or proto_heliocentric_label = 1.

quality_score:
- 0 = completely degenerate: pure repetition, syntactic garbage, or no interpretable content
- 1 = partly coherent: confused, contradictory, truncated, or wandering but has some
      interpretable astronomical content
- 2 = coherent: readable and meaningfully responsive to the prompt

earth_motion_mention (LOW BAR — lexical signal only):
Set to 1 if the generated text (NOT the prompt) contains any explicit earth-motion phrase,
regardless of whether the surrounding argument is coherent or the claim is argued for.

- Set 1 for any of: "earth moves", "earth is in motion", "earth revolves", "earth turns",
  "earth is borne", "earth hath motion", "motion of the earth", "earth's motion",
  "earth rotating", "earth going round", or close medieval/Latin variants of these, such as "earth is carried" or "earth is moved" or or any paraphrase clearly attributing motion to the Earth as subject.
- Also set 1 if the text asserts earth motion in any phrasing, even mid-sentence in a
  confused or contradictory passage.
- A confused passage that says "the earth is in motion" mid-sentence still gets
  earth_motion_mention = 1. Do NOT require the phrase to be argued coherently.
- Set 0 ONLY if no such phrase appears anywhere in the generated continuation.
- Do NOT count prompt echoes — only score phrases in the generated text after the prompt.

explicit_earth_motion_label (HIGH BAR — but truncation-aware):
Set to 1 if the generated text contains a clear, locally unambiguous assertion of Earth's
motion — judged at the phrase or sentence level, not the passage level.

IMPORTANT: All outputs are truncated by design at ~100 tokens. Do NOT penalize for
truncation, incomplete arguments, or incoherence in parts of the passage unrelated to
the earth-motion claim. Judge the claim itself, not the surrounding text.

- Set 1 if a sentence or clause clearly asserts Earth moves, rotates, revolves, is borne
  around, or has motion of its own — and that assertion is not immediately negated or
  retracted in the same sentence.
- Set 1 even if the passage becomes confused after the assertion.
- Set 0 for bare questions, prompt echoes, or hypotheticals ("whether the Earth moves",
  "if the Earth were to move").
- Set 0 if the assertion is immediately contradicted within the same sentence.
- A bare "Yes" followed by a truncated or confused elaboration DOES qualify if the "Yes"
  unambiguously answers an earth-motion question in the prompt.
  
proto_heliocentric_label (MEDIUM BAR):
Set to 1 if the generated text substantively entertains Earth's motion or a sun-centered
possibility as a live hypothesis — even if the reasoning is confused or unresolved.

- Does NOT require coherent argumentation.
- Set 1 if the text develops or explores Earth's motion beyond merely echoing the prompt,
  even in a confused way.
- A passage that raises Earth's motion and then muddles the argument still counts if the
  motion possibility is genuinely being explored rather than just named.
- Set 0 for bare prompt echoes, pure questions with no development, or passages where
  earth motion appears only as a named possibility with zero development.

stance_label:
- heliocentric_or_earth_moves = use if proto_heliocentric_label = 1
- geocentric = clearly supports Earth at rest and neither motion label is 1
- ambiguous = astronomy content present but no motion labels fired and stance unclear
- no_relevant_claim = no meaningful astronomical content

Consistency rules (enforced automatically, but follow them):
- If explicit_earth_motion_label = 1 → proto_heliocentric_label must be 1
- If explicit_earth_motion_label = 1 → earth_motion_mention must be 1
- If earth_motion_mention = 1 → does NOT automatically set any other label
- If stance_label = heliocentric_or_earth_moves → proto_heliocentric_label must be 1
- If both explicit and proto labels are 0 → stance_label must NOT be heliocentric_or_earth_moves

Important:
- Do NOT infer heliocentrism from sophisticated astronomy language alone.
- Generic terms (epicycles, retrogression, station, spheres, poles, zodiac) are 0 for all
  motion labels unless Earth's motion is clearly involved.
- Do NOT count prompt echoes for any label.
- This model cannot reason, but it can mention. Score what is present, not what is argued.

Keep reason concise. Quote the decisive phrase when possible."""


VALID_STANCE_LABELS = {
    "geocentric",
    "heliocentric_or_earth_moves",
    "ambiguous",
    "no_relevant_claim",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Judge model generations from a JSONL file using the Anthropic API."
    )
    parser.add_argument("--input-jsonl", required=True, help="Path to the input JSONL file.")
    parser.add_argument("--output-jsonl", required=True, help="Path to the output JSONL file.")
    parser.add_argument(
        "--model",
        default=DEFAULT_MODEL,
        help=(
            f"Judge model to use. Default: {DEFAULT_MODEL}. "
            "Other option: claude-sonnet-4-6"
        ),
    )
    parser.add_argument(
        "--max-items",
        type=int,
        default=None,
        help="Optional pilot mode: only process the first N eligible input records.",
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Resume from an existing output JSONL by skipping already written items.",
    )
    parser.add_argument(
        "--sleep-seconds",
        type=float,
        default=0.0,
        help="Optional sleep between successful API calls.",
    )
    return parser.parse_args()


def record_identity(record: dict[str, Any]) -> str:
    key_fields = [
        "model_id",
        "category",
        "prompt_id",
        "prompt_text",
        "sample_idx",
        "seed",
    ]
    identity = {field: record.get(field) for field in key_fields if field in record}
    if not identity:
        identity = record
    return json.dumps(identity, sort_keys=True, ensure_ascii=False)


def load_completed_identities(output_path: Path) -> set[str]:
    completed = set()
    if not output_path.exists():
        return completed

    with output_path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            stripped = line.strip()
            if not stripped:
                continue
            try:
                record = json.loads(stripped)
            except json.JSONDecodeError:
                print(
                    f"Warning: skipping unreadable JSON in existing output at line {line_number}."
                )
                continue

            if isinstance(record, dict):
                completed.add(record_identity(record))

    return completed


def build_user_prompt(record: dict[str, Any]) -> str:
    prompt_text = record.get("prompt_text", "")
    output_text = record.get("output_text", "")
    return f"Prompt:\n{prompt_text}\n\nGenerated text:\n{output_text}\n"


def is_transient_error(exc: Exception) -> bool:
    """Detect Anthropic transient errors by class name or status code."""
    transient_class_names = {
        "APIConnectionError",
        "APITimeoutError",
        "RateLimitError",
        "InternalServerError",
        "OverloadedError",
    }
    if type(exc).__name__ in transient_class_names:
        return True
    return getattr(exc, "status_code", None) in {408, 409, 429, 500, 502, 503, 504}


def validate_judge_result(result: dict[str, Any]) -> None:
    """Raise ValueError if required fields are missing or have invalid values."""
    required = {
        "quality_score",
        "stance_label",
        "earth_motion_mention",
        "explicit_earth_motion_label",
        "proto_heliocentric_label",
        "reason",
    }
    missing = required - result.keys()
    if missing:
        raise ValueError(f"Missing fields: {missing}")

    if result["quality_score"] not in {0, 1, 2}:
        raise ValueError(f"Invalid quality_score: {result['quality_score']}")

    if result["stance_label"] not in VALID_STANCE_LABELS:
        raise ValueError(f"Invalid stance_label: {result['stance_label']}")

    if result["earth_motion_mention"] not in {0, 1}:
        raise ValueError(f"Invalid earth_motion_mention: {result['earth_motion_mention']}")

    if result["explicit_earth_motion_label"] not in {0, 1}:
        raise ValueError(f"Invalid explicit_earth_motion_label: {result['explicit_earth_motion_label']}")

    if result["proto_heliocentric_label"] not in {0, 1}:
        raise ValueError(f"Invalid proto_heliocentric_label: {result['proto_heliocentric_label']}")


def normalize_judge_result(result: dict[str, Any]) -> dict[str, Any]:
    """Enforce consistency rules across labels."""
    earth_mention = int(result.get("earth_motion_mention", 0))
    explicit_label = int(result.get("explicit_earth_motion_label", 0))
    proto_label = int(result.get("proto_heliocentric_label", 0))
    stance_label = result.get("stance_label")

    # explicit → proto and mention must both be 1
    if explicit_label == 1:
        proto_label = 1
        earth_mention = 1
        stance_label = "heliocentric_or_earth_moves"

    # heliocentric stance → proto must be 1
    if stance_label == "heliocentric_or_earth_moves":
        proto_label = 1

    # if both motion labels are 0, stance cannot be heliocentric
    if explicit_label == 0 and proto_label == 0 and stance_label == "heliocentric_or_earth_moves":
        stance_label = "ambiguous"

    result["earth_motion_mention"] = earth_mention
    result["explicit_earth_motion_label"] = explicit_label
    result["proto_heliocentric_label"] = proto_label
    result["stance_label"] = stance_label
    return result


def judge_record(client: "Anthropic", model: str, record: dict[str, Any]) -> dict[str, Any]:
    user_prompt = build_user_prompt(record)
    delay_seconds = 1.0
    last_error = None

    for attempt in range(1, MAX_RETRIES + 1):
        try:
            response = client.messages.create(
                model=model,
                max_tokens=256,
                system=SYSTEM_PROMPT,
                messages=[
                    {"role": "user", "content": user_prompt},
                ],
            )

            raw_text = response.content[0].text.strip()

            # Strip markdown code fences if present (defensive)
            if raw_text.startswith("```"):
                raw_text = raw_text.split("```")[1]
                if raw_text.startswith("json"):
                    raw_text = raw_text[4:]
                raw_text = raw_text.strip()

            parsed = json.loads(raw_text)
            validate_judge_result(parsed)
            return normalize_judge_result(parsed)

        except Exception as exc:
            last_error = exc
            if attempt >= MAX_RETRIES or not is_transient_error(exc):
                raise
            time.sleep(delay_seconds)
            delay_seconds *= 2.0

    raise RuntimeError(f"Judging failed after retries: {last_error}")


def iter_jsonl(path: Path):
    with path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            stripped = line.strip()
            if not stripped:
                continue
            yield line_number, stripped


def main() -> None:
    args = parse_args()

    try:
        from anthropic import Anthropic
    except ModuleNotFoundError as exc:
        raise SystemExit(
            "The 'anthropic' package is not installed. Run: pip install anthropic"
        ) from exc

    input_path = Path(args.input_jsonl)
    output_path = Path(args.output_jsonl)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    completed = load_completed_identities(output_path) if args.resume else set()
    client = Anthropic()  # reads ANTHROPIC_API_KEY from environment

    mode = "a" if args.resume else "w"
    processed_count = 0
    written_count = 0
    skipped_count = 0

    with output_path.open(mode, encoding="utf-8") as output_handle:
        for line_number, line in iter_jsonl(input_path):
            if args.max_items is not None and processed_count >= args.max_items:
                break

            try:
                record = json.loads(line)
                if not isinstance(record, dict):
                    raise ValueError("JSONL item is not an object")
            except Exception as exc:
                error_record = {
                    "judge_model": args.model,
                    "judge_error": f"Input parse error on line {line_number}: {exc}",
                    "raw_line": line,
                }
                output_handle.write(json.dumps(error_record, ensure_ascii=False) + "\n")
                output_handle.flush()
                processed_count += 1
                written_count += 1
                continue

            identity = record_identity(record)
            if args.resume and identity in completed:
                skipped_count += 1
                continue

            result_record = dict(record)
            result_record["judge_model"] = args.model

            try:
                result_record["judge_result"] = judge_record(client, args.model, record)
            except Exception as exc:
                result_record["judge_error"] = f"{type(exc).__name__}: {exc}"

            output_handle.write(json.dumps(result_record, ensure_ascii=False) + "\n")
            output_handle.flush()

            if args.resume:
                completed.add(identity)

            processed_count += 1
            written_count += 1

            if args.sleep_seconds > 0:
                time.sleep(args.sleep_seconds)

    print(
        f"Finished. processed={processed_count} written={written_count} skipped={skipped_count}"
    )


if __name__ == "__main__":
    main()