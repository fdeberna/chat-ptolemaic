def record_identity(record: dict[str, Any]) -> str:
    key_fields = [
        "model_name",
        "adapter_dir",
        "prompt_file",
        "prompt_category",
        "prompt_id",
        "sample_id",
    ]
    identity = {field: record.get(field) for field in key_fields}
    return json.dumps(identity, sort_keys=True, ensure_ascii=False)


def load_completed_identities(output_path: Path) -> set[str]:
    completed: set[str] = set()
    if not output_path.exists():
        return completed

    with output_path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            stripped = line.strip()
            if not stripped:
                continue
            try:
                record = json.loads(stripped)
            except json.JSONDecodeError:
                print(
                    f"Warning: skipping unreadable JSON in existing output at line {line_number}."
                )
                continue
            if isinstance(record, dict):
                completed.add(record_identity(record))
    return completed


def iter_jsonl(path: Path):
    with path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            stripped = line.strip()
            if not stripped:
                continue
            yield line_number, stripped


def ensure_output_mode(output_path: Path, resume: bool, overwrite: bool) -> str:
    if output_path.exists() and not resume and not overwrite:
        raise SystemExit(
            f"Output JSONL already exists: {output_path}. Use --resume or --overwrite."
        )
    return "a" if resume else "w"


def build_user_prompt(record: dict[str, Any]) -> str:
    prompt = record.get("prompt", "")
    completion = record.get("completion", "")
    prompt_category = record.get("prompt_category", "")
    prompt_id = record.get("prompt_id", "")
    return (
        f"Prompt category: {prompt_category}\n"
        f"Prompt id: {prompt_id}\n\n"
        f"Original prompt:\n{prompt}\n\n"
        f"Model completion:\n{completion}\n"
    )


def is_transient_error(exc: Exception) -> bool:
    transient_class_names = {
        "APIConnectionError",
        "APITimeoutError",
        "RateLimitError",
        "InternalServerError",
        "OverloadedError",
    }
    if type(exc).__name__ in transient_class_names:
        return True
    return getattr(exc, "status_code", None) in {408, 409, 429, 500, 502, 503, 504}


def strip_code_fences(text: str) -> str:
    stripped = text.strip()
    if not stripped.startswith("```"):
        return stripped

    parts = stripped.split("```")
    if len(parts) < 3:
        return stripped

    inner = parts[1].strip()
    if inner.startswith("json"):
        inner = inner[4:].strip()
    return inner


def extract_first_json_object(text: str) -> str | None:
    start = text.find("{")
    if start < 0:
        return None

    depth = 0
    in_string = False
    escape = False

    for index in range(start, len(text)):
        char = text[index]
        if in_string:
            if escape:
                escape = False
            elif char == "\\":
                escape = True
            elif char == '"':
                in_string = False
            continue

        if char == '"':
            in_string = True
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return text[start : index + 1]

    return None


def parse_possible_json(raw_text: str) -> dict[str, Any]:
    candidates = [
        raw_text,
        raw_text.strip(),
        strip_code_fences(raw_text),
    ]
    extracted = extract_first_json_object(raw_text)
    if extracted:
        candidates.append(extracted)

    seen: set[str] = set()
    last_error: Exception | None = None

    for candidate in candidates:
        if not candidate or candidate in seen:
            continue
        seen.add(candidate)
        try:
            parsed = json.loads(candidate)
        except Exception as exc:
            last_error = exc
            continue
        if not isinstance(parsed, dict):
            raise ValueError("Judge output JSON was not an object.")
        return parsed

    raise ValueError(f"Unable to parse judge JSON: {last_error}")


def coerce_bool(value: Any, field_name: str) -> bool:
    if isinstance(value, bool):
        return value
    if value in {0, 1}:
        return bool(value)
    if isinstance(value, str):
        normalized = value.strip().lower()
        if normalized in {"true", "1", "yes"}:
            return True
        if normalized in {"false", "0", "no"}:
            return False
    raise ValueError(f"Invalid boolean for {field_name}: {value!r}")


def coerce_explicit_label(value: Any) -> str:
    if value in {0, 1}:
        return "earth_moves" if int(value) == 1 else "none"
    if not isinstance(value, str):
        raise ValueError(f"Invalid explicit_earth_motion_label: {value!r}")
    normalized = value.strip().lower()
    if normalized in {"moves", "earth_move", "earth_moving"}:
        normalized = "earth_moves"
    if normalized in EXPLICIT_LABELS:
        return normalized
    raise ValueError(f"Invalid explicit_earth_motion_label: {value!r}")


def coerce_proto_label(value: Any) -> str:
    if value in {0, 1}:
        return "strong" if int(value) == 1 else "none"
    if not isinstance(value, str):
        raise ValueError(f"Invalid proto_heliocentric_label: {value!r}")
    normalized = value.strip().lower()
    if normalized in {"proto", "present"}:
        normalized = "strong"
    if normalized in PROTO_LABELS:
        return normalized
    raise ValueError(f"Invalid proto_heliocentric_label: {value!r}")


def coerce_stance(value: Any) -> str:
    if not isinstance(value, str):
        raise ValueError(f"Invalid stance: {value!r}")
    normalized = value.strip().lower()
    if normalized == "heliocentric":
        normalized = "heliocentric_or_earth_moves"
    if normalized == "irrelevant_or_unclear":
        normalized = "no_relevant_claim"
    if normalized in STANCE_LABELS:
        return normalized
    raise ValueError(f"Invalid stance: {value!r}")


def coerce_refined_stance(value: Any) -> str:
    if not isinstance(value, str):
        raise ValueError(f"Invalid refined_stance: {value!r}")
    normalized = value.strip().lower()
    if normalized in REFINED_STANCE_LABELS:
        return normalized
    raise ValueError(f"Invalid refined_stance: {value!r}")


def coerce_earth_motion_context(value: Any) -> str:
    if not isinstance(value, str):
        raise ValueError(f"Invalid earth_motion_context: {value!r}")
    normalized = value.strip().lower()
    if normalized in EARTH_MOTION_CONTEXT_LABELS:
        return normalized
    raise ValueError(f"Invalid earth_motion_context: {value!r}")


def validate_and_normalize_result(result: dict[str, Any]) -> dict[str, Any]:
    required_fields = {
        "quality_score",
        "earth_motion_mention",
        "explicit_earth_motion_label",
        "proto_heliocentric_label",
        "stance",
        "refined_stance",
        "off_topic_or_drift",
        "repetition_or_looping",
        "premodern_register",
        "refined_proto_heliocentric_label",
        "earth_motion_context",
        "hybrid_or_contradictory_frame",
        "modern_explanatory_frame",
        "premodern_explanatory_frame",
        "rationale",
    }
    missing = required_fields - result.keys()
    if missing:
        raise ValueError(f"Missing fields: {sorted(missing)}")

    normalized = {
        "quality_score": int(result["quality_score"]),
        "earth_motion_mention": coerce_bool(result["earth_motion_mention"], "earth_motion_mention"),
        "explicit_earth_motion_label": coerce_explicit_label(
            result["explicit_earth_motion_label"]
        ),
        "proto_heliocentric_label": coerce_proto_label(result["proto_heliocentric_label"]),
        "stance": coerce_stance(result["stance"]),
        "refined_stance": coerce_refined_stance(result["refined_stance"]),
        "off_topic_or_drift": coerce_bool(result["off_topic_or_drift"], "off_topic_or_drift"),
        "repetition_or_looping": coerce_bool(
            result["repetition_or_looping"], "repetition_or_looping"
        ),
        "premodern_register": str(result["premodern_register"]).strip().lower(),
        "refined_proto_heliocentric_label": coerce_proto_label(
            result["refined_proto_heliocentric_label"]
        ),
        "earth_motion_context": coerce_earth_motion_context(result["earth_motion_context"]),
        "hybrid_or_contradictory_frame": coerce_bool(
            result["hybrid_or_contradictory_frame"], "hybrid_or_contradictory_frame"
        ),
        "modern_explanatory_frame": coerce_bool(
            result["modern_explanatory_frame"], "modern_explanatory_frame"
        ),
        "premodern_explanatory_frame": coerce_bool(
            result["premodern_explanatory_frame"], "premodern_explanatory_frame"
        ),
        "rationale": str(result["rationale"]).strip(),
    }

    if normalized["quality_score"] not in {0, 1, 2}:
        raise ValueError(f"Invalid quality_score: {normalized['quality_score']}")
    if normalized["premodern_register"] not in PREMODERN_REGISTER_LABELS:
        raise ValueError(f"Invalid premodern_register: {normalized['premodern_register']!r}")

    explicit_label = normalized["explicit_earth_motion_label"]
    legacy_proto_label = normalized["proto_heliocentric_label"]
    stance = normalized["stance"]
    refined_proto_label = normalized["refined_proto_heliocentric_label"]
    refined_stance = normalized["refined_stance"]

    if explicit_label == "earth_moves":
        normalized["earth_motion_mention"] = True
        if legacy_proto_label in {"none", "unclear"}:
            legacy_proto_label = "strong"
        stance = "heliocentric_or_earth_moves"

    if explicit_label == "earth_stationary" and stance in {
        "heliocentric_or_earth_moves",
        "no_relevant_claim",
    }:
        stance = "geocentric"

    if legacy_proto_label in {"weak", "strong"} and stance == "no_relevant_claim":
        stance = "heliocentric_or_earth_moves"

    if legacy_proto_label == "none" and stance == "heliocentric_or_earth_moves":
        if explicit_label == "earth_stationary":
            stance = "geocentric"
        else:
            stance = "ambiguous"

    if refined_proto_label in {"weak", "strong"} and normalized["earth_motion_context"] == "none":
        normalized["earth_motion_context"] = "ambiguous_or_mixed"

    if normalized["hybrid_or_contradictory_frame"] and refined_stance not in {
        "hybrid_or_contradictory",
        "irrelevant_or_unclear",
    }:
        refined_stance = "hybrid_or_contradictory"

    normalized["proto_heliocentric_label"] = legacy_proto_label
    normalized["stance"] = stance
    normalized["stance_label"] = stance
    normalized["stance_normalized"] = normalize_stance_label(stance)
    normalized["refined_stance"] = refined_stance
    normalized["explicit_earth_motion_binary"] = explicit_label == "earth_moves"
    normalized["proto_heliocentric_binary"] = legacy_proto_label in {"weak", "strong"}
    normalized["refined_proto_heliocentric_binary"] = refined_proto_label in {"weak", "strong"}
    normalized["reason"] = normalized["rationale"]
    return normalized


def normalize_stance_label(value: str) -> str:
    mapping = {
        "geocentric": "geocentric",
        "heliocentric_or_earth_moves": "heliocentric",
        "ambiguous": "ambiguous",
        "no_relevant_claim": "irrelevant_or_unclear",
    }
    return mapping[value]


def repair_judge_output(
    client: "Anthropic",
    model: str,
    raw_text: str,
) -> dict[str, Any]:
    response = client.messages.create(
        model=model,
        max_tokens=512,
        system=REPAIR_SYSTEM_PROMPT,
        messages=[
            {
                "role": "user",
                "content": (
                    "Repair this malformed judge output into a valid JSON object:\n\n"
                    f"{raw_text}"
                ),
            }
        ],
    )
    raw_text = response.content[0].text.strip()
    return validate_and_normalize_result(parse_possible_json(raw_text))


def judge_record(client: "Anthropic", model: str, record: dict[str, Any]) -> dict[str, Any]:
    user_prompt = build_user_prompt(record)
    delay_seconds = 1.0
    last_error: Exception | None = None

    for attempt in range(1, MAX_RETRIES + 1):
        try:
            response = client.messages.create(
                model=model,
                max_tokens=512,
                system=SYSTEM_PROMPT,
                messages=[
                    {"role": "user", "content": user_prompt},
                ],
            )
            raw_text = response.content[0].text.strip()
            try:
                return validate_and_normalize_result(parse_possible_json(raw_text))
            except Exception:
                return repair_judge_output(client, model, raw_text)
        except Exception as exc:
            last_error = exc
            if attempt >= MAX_RETRIES or not is_transient_error(exc):
                raise
            time.sleep(delay_seconds)
            delay_seconds *= 2.0

    raise RuntimeError(f"Judging failed after retries: {last_error}")


def main() -> None:
    args = parse_args()

    try:
        from anthropic import Anthropic
    except ModuleNotFoundError as exc:
        raise SystemExit(
            "The 'anthropic' package is not installed. Run: pip install anthropic"
        ) from exc

    input_path = Path(args.input_jsonl)
    output_path = Path(args.output_jsonl)

    if not input_path.exists():
        raise SystemExit(f"Input JSONL not found: {input_path}")
    if args.max_rows is not None and args.max_rows <= 0:
        raise SystemExit("--max-rows must be positive when provided.")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    mode = ensure_output_mode(output_path, resume=args.resume, overwrite=args.overwrite)
    completed = load_completed_identities(output_path) if args.resume else set()
    client = Anthropic()

    processed_count = 0
    written_count = 0
    skipped_count = 0

    with output_path.open(mode, encoding="utf-8") as output_handle:
        for line_number, line in iter_jsonl(input_path):
            if args.max_rows is not None and processed_count >= args.max_rows:
                break

            try:
                record = json.loads(line)
                if not isinstance(record, dict):
                    raise ValueError("JSONL row is not an object")
            except Exception as exc:
                error_record = {
                    "judge_model": args.judge_model,
                    "judge_timestamp": datetime.now(timezone.utc).isoformat(),
                    "judge_error": f"Input parse error on line {line_number}: {exc}",
                    "raw_line": line,
                }
                output_handle.write(json.dumps(error_record, ensure_ascii=False) + "\n")
                output_handle.flush()
                processed_count += 1
                written_count += 1
                continue

            identity = record_identity(record)
            if args.resume and identity in completed:
                skipped_count += 1
                continue

            result_record = dict(record)
            result_record["judge_model"] = args.judge_model
            result_record["judge_timestamp"] = datetime.now(timezone.utc).isoformat()

            try:
                result_record["judge_result"] = judge_record(client, args.judge_model, record)
            except Exception as exc:
                result_record["judge_error"] = f"{type(exc).__name__}: {exc}"

            output_handle.write(json.dumps(result_record, ensure_ascii=False) + "\n")
            output_handle.flush()

            if args.resume:
                completed.add(identity)

            processed_count += 1
            written_count += 1

            if args.sleep_seconds > 0:
                time.sleep(args.sleep_seconds)

    print(
        f"Finished. processed={processed_count} written={written_count} skipped={skipped_count}"
    )


if __name__ == "__main__":
    main()
